const patterns = [
  [/^[Сс]ерия (\d+)$/, "Episodio $1"],
  [/^из ([\d?]+)$/, "de $1"],
  [/^Доступно серий: (\d+)$/, "$1 episodios disponibles"],
  [/^(\d+ \/ [\d—]+) просмотрено$/, "$1 vistos"],
  [/^Комната ([A-Z\d]+) ·$/, "Sala $1 ·"],
  [/^· чат в реальном времени$/, "· chat en tiempo real"],
  [/^Выбрана: (.+)$/, "Audio: $1"],
  [/^Серия (\d+|—)( · .+)?$/, "Episodio $1$2"],
  [/^(\d+) релизов$/, "$1 estrenos"],
  [/^(\d+) рел\.$/, "$1 estr."],
  [/^Загрузить серию (\d+)$/, "Cargar episodio $1"],
  [/^Основной плеер · (.+) · серия (\d+)$/, "Reproductor principal · $1 · episodio $2"]
];

function translated(value) {
  const trimmed = value.trim();
  const label = labels.get(trimmed) ?? patterns.reduce((current, [match, result]) => current.replace(match, result), trimmed);
  return label === trimmed ? value : value.replace(trimmed, label);
}

export function translateLabels(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (node.parentElement?.closest("script, style, #ms, .anime-card-title, .calendar-title, [data-user-text], .anime-description")) return;
    const value = translated(node.data);
    if (node.data !== value) node.data = value;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const name of ["title", "placeholder", "aria-label"]) {
    const current = node.getAttribute(name);
    if (current === null) continue;
    const value = translated(current);
    if (value !== current) node.setAttribute(name, value);
  }
  for (const child of node.childNodes) translateLabels(child);
}
